// scanDeck scans a single row into a model.Deck.
func scanDeck(row pgx.Row) (*model.Deck, error) {
	var d model.Deck
	err := row.Scan(
		&d.PlayerID,
		&d.DeckID,
		&d.DeckName,
		&d.PlaymatNo,
		&d.SleeveNo,
		&d.CreatedAt,
		&d.UpdatedAt,
	)
	if err != nil {
		return nil, err
	}
	return &d, nil
}

// bulkInsertDeckCards inserts multiple deck_cards rows in a single INSERT statement.
func bulkInsertDeckCards(ctx context.Context, db dbtx, cards []model.DeckCard) error {
	if len(cards) == 0 {
		return nil
	}

	var sb strings.Builder
	sb.WriteString("INSERT INTO deck_cards (player_id, deck_id, card_id, art_no, count) VALUES ")

	args := make([]interface{}, 0, len(cards)*5)
	for i, c := range cards {
		if i > 0 {
			sb.WriteString(",")
		}
		base := i*5 + 1
		fmt.Fprintf(&sb, "($%d,$%d,$%d,$%d,$%d)", base, base+1, base+2, base+3, base+4)
		args = append(args, c.PlayerID, c.DeckID, c.CardID, c.ArtNo, c.Count)
	}

	_, err := db.Exec(ctx, sb.String(), args...)
	if err != nil {
		return fmt.Errorf("insert deck cards: %w", err)
	}
	return nil
}
